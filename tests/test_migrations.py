from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect

from app.env import env

ALEMBIC_INI = Path(__file__).parents[1] / 'alembic.ini'


@pytest.fixture
def alembic_config(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Config:
    # migrations/env.py reads the URL from app.env, so point it at a fresh file.
    monkeypatch.setattr(env, 'DATABASE_URL', f'sqlite:///{tmp_path / "test.db"}')
    return Config(ALEMBIC_INI)


def test_upgrade_head_creates_item_table(alembic_config: Config) -> None:
    command.upgrade(alembic_config, 'head')

    columns = inspect(create_engine(env.DATABASE_URL)).get_columns('item')
    assert [column['name'] for column in columns] == ['id', 'name']


def test_migrations_match_models(alembic_config: Config) -> None:
    command.upgrade(alembic_config, 'head')
    # Raises AutogenerateDiffsDetected if the models changed without a migration.
    command.check(alembic_config)
